import test from 'node:test';
import assert from 'node:assert/strict';
import { parseCodexLine } from '../src/parsers/codex.mjs';
import { parseCursorLine } from '../src/parsers/cursor.mjs';

test('parses codex thread, item and turn.completed events', () => {
  assert.equal(parseCodexLine('not json'), null);
  assert.equal(parseCodexLine(''), null);
  const thread = parseCodexLine('{"type":"thread.started","thread_id":"thread-1"}');
  assert.equal(thread.kind, 'thread.started');
  assert.equal(thread.thread_id, 'thread-1');
  assert.equal(parseCodexLine('{"type":"turn.started"}').kind, 'other');
  const started = parseCodexLine('{"type":"item.started","item":{"id":"item_1","type":"command_execution","command":"ls","status":"in_progress"}}');
  assert.equal(started.kind, 'item');
  assert.equal(started.phase, 'started');
  assert.equal(started.command, 'ls');
  const updated = parseCodexLine('{"type":"item.updated","item":{"id":"item_1","type":"command_execution","aggregated_output":"a\\n"}}');
  assert.equal(updated.phase, 'updated');
  assert.equal(updated.aggregated_output, 'a\n');
  const message = parseCodexLine('{"type":"item.completed","item":{"id":"item_3","type":"agent_message","text":"Done."}}');
  assert.equal(message.phase, 'completed');
  assert.equal(message.item_type, 'agent_message');
  assert.equal(message.text, 'Done.');
  const turn = parseCodexLine('{"type":"turn.completed","usage":{"input_tokens":10,"cached_input_tokens":4,"output_tokens":3,"reasoning_output_tokens":1}}');
  assert.equal(turn.kind, 'turn.completed');
  assert.equal(turn.usage.input_tokens, 10);
  assert.equal(turn.usage.cached_input_tokens, 4);
  const failed = parseCodexLine('{"type":"turn.failed","error":{"message":"boom"}}');
  assert.equal(failed.kind, 'turn.failed');
  assert.equal(failed.message, 'boom');
  assert.equal(parseCodexLine('{"type":"error","message":"nope"}').kind, 'error');
});

test('parses cursor init, partial assistant text, tool_call and result', () => {
  assert.equal(parseCursorLine('{'), null);
  const init = parseCursorLine('{"type":"system","subtype":"init","session_id":"sess-1","model":"grok-4.7-medium"}');
  assert.equal(init.kind, 'system_init');
  assert.equal(init.session_id, 'sess-1');
  assert.equal(init.model, 'grok-4.7-medium');
  const partial = parseCursorLine('{"type":"assistant","timestamp_ms":1774949076041,"message":{"role":"assistant","content":[{"type":"text","text":"Hel"}]}}');
  assert.equal(partial.kind, 'assistant_partial');
  assert.equal(partial.partial, true);
  assert.equal(partial.model_call_id, null);
  assert.equal(partial.text, 'Hel');
  const flush = parseCursorLine('{"type":"assistant","timestamp_ms":1774949076838,"model_call_id":"call-1","message":{"content":[{"type":"text","text":"Hello"}]}}');
  assert.equal(flush.kind, 'assistant');
  assert.equal(flush.partial, false);
  assert.equal(flush.model_call_id, 'call-1');
  const finalFlush = parseCursorLine('{"type":"assistant","message":{"content":[{"type":"text","text":"Hello"}]}}');
  assert.equal(finalFlush.kind, 'assistant');
  assert.equal(finalFlush.partial, false);
  assert.equal(finalFlush.timestamp_ms, null);
  const tool = parseCursorLine('{"type":"tool_call","subtype":"started","call_id":"toolu_1","tool_call":{"readToolCall":{"args":{"path":"a.js"}}}}');
  assert.equal(tool.kind, 'tool_call');
  assert.equal(tool.subtype, 'started');
  assert.equal(tool.name, 'read');
  assert.equal(tool.call_id, 'toolu_1');
  const result = parseCursorLine('{"type":"result","subtype":"success","is_error":false,"result":"done","session_id":"sess-1"}');
  assert.equal(result.kind, 'result');
  assert.equal(result.is_error, false);
  assert.equal(result.text, 'done');
  const failed = parseCursorLine('{"type":"result","subtype":"error","result":"bad"}');
  assert.equal(failed.is_error, true);
});
